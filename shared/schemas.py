from datetime import datetime
from typing import Annotated, Any, Optional
from pydantic import BaseModel, BeforeValidator, Field, PlainSerializer, WithJsonSchema
from bson import ObjectId


# ─────────────────────────────────────────────
# HELPER — make ObjectId work with Pydantic v2
# ─────────────────────────────────────────────

def _validate_object_id(v: Any) -> ObjectId:
    if isinstance(v, ObjectId):
        return v
    if not ObjectId.is_valid(str(v)):
        raise ValueError(f"Invalid ObjectId: {v}")
    return ObjectId(str(v))


PyObjectId = Annotated[
    ObjectId,
    BeforeValidator(_validate_object_id),
    PlainSerializer(str),
    WithJsonSchema({"type": "string"}),
]


# ─────────────────────────────────────────────
# CORE DOCUMENT — stored in MongoDB `chunks`
# ─────────────────────────────────────────────

class ChunkDocument(BaseModel):
    """
    The single source of truth for what lives in MongoDB.

    Dev A writes:   source_file, chunk_index, text, metadata
    Dev B writes:   embedding, embedding_model, embedded_at
    """

    id: Optional[PyObjectId] = Field(default=None, alias="_id")

    # ── Populated by Dev A (ingestion pipeline) ──
    source_file: str           # e.g. "docs/report_2024.pdf"
    chunk_index: int           # position of this chunk within its source file
    text: str                  # raw text content of the chunk
    char_count: int            # len(text) — for diagnostics
    metadata: "ChunkMetadata"  # see below

    # ── Populated by Dev B (embedding pipeline) ──
    embedding: Optional[list[float]] = None     # vector from the local model
    embedding_model: Optional[str] = None       # e.g. "nomic-embed-text"
    embedded_at: Optional[datetime] = None      # UTC timestamp

    class Config:
        populate_by_name = True
        arbitrary_types_allowed = True
        json_encoders = {ObjectId: str}


class ChunkMetadata(BaseModel):
    """
    Flexible metadata attached to every chunk.
    Add fields here as needed — just tell your coworker.
    """
    doc_type: str                       # e.g. "pdf", "markdown", "txt"
    section_title: Optional[str] = None # heading above this chunk if detectable
    page_number: Optional[int] = None   # relevant for PDFs
    language: Optional[str] = "en"
    tags: list[str] = []                # optional manual labels


# ─────────────────────────────────────────────
# API REQUEST / RESPONSE SHAPES
# (used by Dev A in FastAPI routes)
# ─────────────────────────────────────────────

class QueryRequest(BaseModel):
    """
    Body of POST /query
    """
    question: str = Field(..., min_length=1, max_length=1000)
    top_k: int = Field(default=5, ge=1, le=20)
    doc_type_filter: Optional[str] = None   # e.g. "pdf" to limit search scope


class RetrievedChunk(BaseModel):
    """
    A single chunk returned from the retrieval step, with its similarity score.
    """
    chunk_id: str
    text: str
    score: float                        # cosine similarity — range [0.0, 1.0]
    source_file: str
    metadata: ChunkMetadata


class QueryResponse(BaseModel):
    """
    Final response from POST /query
    """
    question: str
    answer: str                         # generated by the local LLM
    retrieved_chunks: list[RetrievedChunk]
    model_used: str                     # e.g. "mistral:7b"
    latency_ms: float


# ─────────────────────────────────────────────
# INGESTION PIPELINE TYPES
# (used internally by Dev A)
# ─────────────────────────────────────────────

class RawDocument(BaseModel):
    """
    Intermediate object: a loaded file before chunking.
    """
    source_file: str
    doc_type: str
    raw_text: str
    page_count: Optional[int] = None


class ChunkInput(BaseModel):
    """
    What Dev A passes to Dev B's embed() function.
    Agree on this — it's the handoff point.
    """
    text: str
    source_file: str
    chunk_index: int
    metadata: ChunkMetadata
